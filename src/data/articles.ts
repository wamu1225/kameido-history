昭和22年（1947年）、東京都の特別区制度への移行にともなって、区の再編が行われます。城東区会は2月21日、深川区会は2月25日にそれぞれ合併を議決し、3月15日に両区が合併して「江東区」が誕生しました。区名の「江」は深川、「東」は城東を表しているとされます。亀戸は、こうして城東区の一部から江東区の一部になりました。

